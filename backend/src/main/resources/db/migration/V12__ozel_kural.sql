-- Kural kurucu (MK-16): yönetici tanımlı kurallar. Tek tablo; silme yok (kapatma = siddet 'KAPALI'); kod saklanmaz ("Ö-" + %03d id).
-- Kapsam (hat, araç tipi, kalkış/varış garı, tren türü, vardiya) kural.Kapsam kaydının JSON'udur: SQL'de kapsama göre sorgu yoktur, tanımlar silinemediği
-- için asılı kimlik oluşamaz, kimlik doğrulaması serviste yapılır. Sürüm geçmişi: satır `versiyon` (eşzamanlı düzenleme 409) + degisiklik_kaydi (eski -> yeni JSON).
-- olcu/pencere CHECK listeleri K2 sabitlerini (seri/boşluk ölçüleri, kayan pencere) önceden kapsar: K2 yeni migration gerektirmez; K1 katalogu bunların bir kısmını sunar.
CREATE TABLE ozel_kural (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad              VARCHAR(80)  NOT NULL,
    olcu            VARCHAR(40)  NOT NULL,
    pencere         VARCHAR(10)  NOT NULL,
    karsilastirma   VARCHAR(10)  NOT NULL,
    esik            NUMERIC(10, 2) NOT NULL,
    kapsam          TEXT         NOT NULL,
    siddet          VARCHAR(10)  NOT NULL,
    gecerlilik_bas  DATE         NOT NULL,
    gecerlilik_bit  DATE,
    gerekce         VARCHAR(500) NOT NULL,
    kaynak          VARCHAR(200),
    versiyon        BIGINT       NOT NULL DEFAULT 0,
    olusturan       VARCHAR(120) NOT NULL,
    olusturma       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    guncelleme      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ozel_kural_olcu_ck CHECK (olcu IN ('TOPLAM_GOREV_SURESI', 'GECE_SURESI', 'TEK_SEFER_SURESI', 'GOREV_SAYISI', 'GECE_NOBETI_SAYISI',
        'ARDISIK_CALISMA_GUNU', 'ARDISIK_GECE_GUNU', 'GOREVSIZ_ARALIK', 'IZIN_GUNU', 'NOBETLER_ARASI_DINLENME')),
    CONSTRAINT ozel_kural_pencere_ck CHECK (pencere IN ('SEFER', 'NOBET', 'GUN', 'HAFTA', 'AY', 'YIL', 'KAYAN', 'SERI')),
    CONSTRAINT ozel_kural_karsilastirma_ck CHECK (karsilastirma IN ('EN_FAZLA', 'EN_AZ')),
    CONSTRAINT ozel_kural_siddet_ck CHECK (siddet IN ('ENGEL', 'UYARI', 'KAPALI')),
    CONSTRAINT ozel_kural_esik_ck CHECK (esik >= 0),
    CONSTRAINT ozel_kural_gecerlilik_ck CHECK (gecerlilik_bit IS NULL OR gecerlilik_bit >= gecerlilik_bas)
);

CREATE UNIQUE INDEX ozel_kural_ad_uk ON ozel_kural (lower(ad));
