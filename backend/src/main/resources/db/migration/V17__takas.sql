-- F2a-3 (MK-34): takas / görev bırakma talebi. Tek tablo. Atama, sefer, makinist kimlikleri düz sayıdır, FK YOK: atama silme yolları (ata/kaldir/takasUygula/demo sıfırlama) bozulmasın.
-- Demo sıfırlama atama kimliklerini sıfırlar ve CASCADE bu tabloya ulaşmaz: DemoVeriServisi TRUNCATE listesinde bu tablo açıkça vardır.
-- Bayatlık ve süre aşımı okumada TÜRETİLİR (kalıcı geçiş yalnız yazma yollarında); bu yüzden durum sütununda BAYAT/SURESI_DOLDU yalnız bir yazma yolu kapattığında görünür.
CREATE TABLE takas_talebi (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tur                     VARCHAR(10)  NOT NULL,
    durum                   VARCHAR(30)  NOT NULL,
    kaynak_atama_id         BIGINT       NOT NULL,
    kaynak_makinist_id      BIGINT       NOT NULL,
    kaynak_sefer_id         BIGINT       NOT NULL,
    kaynak_ozet             TEXT         NOT NULL,
    hedef_atama_id          BIGINT,
    hedef_makinist_id       BIGINT,
    hedef_sefer_id          BIGINT,
    hedef_ozet              TEXT,
    neden                   VARCHAR(20)  NOT NULL,
    neden_notu              VARCHAR(120),
    olusturan_kullanici_id  BIGINT       NOT NULL,
    olusturma               TIMESTAMPTZ  NOT NULL,
    karsi_karar             TIMESTAMPTZ,
    karar_veren             VARCHAR(200),
    karar_zaman             TIMESTAMPTZ,
    son_kalkis              TIMESTAMPTZ  NOT NULL,
    versiyon                BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT takas_tur_ck CHECK (tur IN ('TAKAS', 'BIRAK')),
    CONSTRAINT takas_durum_ck CHECK (durum IN ('KARSI_ONAY_BEKLIYOR', 'ATAMACI_ONAYI_BEKLIYOR', 'ONAYLANDI', 'REDDEDILDI', 'IPTAL', 'SURESI_DOLDU', 'BAYAT')),
    CONSTRAINT takas_neden_ck CHECK (neden IN ('HASTALIK', 'IZIN', 'DIGER')),
    -- karşılıklı takasta hedef alanları tam dolu, bırakmada tam boş
    CONSTRAINT takas_hedef_ck CHECK ((tur = 'TAKAS') = (hedef_atama_id IS NOT NULL AND hedef_makinist_id IS NOT NULL AND hedef_sefer_id IS NOT NULL AND hedef_ozet IS NOT NULL)),
    CONSTRAINT takas_hedef_bos_ck CHECK (tur = 'TAKAS' OR (hedef_atama_id IS NULL AND hedef_makinist_id IS NULL AND hedef_sefer_id IS NULL AND hedef_ozet IS NULL)),
    CONSTRAINT takas_ayni_sefer_ck CHECK (hedef_sefer_id IS NULL OR hedef_sefer_id <> kaynak_sefer_id),
    CONSTRAINT takas_ayni_makinist_ck CHECK (hedef_makinist_id IS NULL OR hedef_makinist_id <> kaynak_makinist_id),
    -- bırakmada karşı onay yoktur
    CONSTRAINT takas_birak_durum_ck CHECK (tur = 'TAKAS' OR durum <> 'KARSI_ONAY_BEKLIYOR')
);

-- Bir atama aynı anda en çok bir AÇIK talepte yer alır: kaynak olarak ve hedef olarak ayrı kısmi UNIQUE (arka güvence). Bir atamanın bir talepte kaynak, başkasında hedef olması
-- (çapraz durum) serviste makinist kilidi altında denetlenir.
CREATE UNIQUE INDEX takas_kaynak_acik_uk ON takas_talebi (kaynak_atama_id) WHERE durum IN ('KARSI_ONAY_BEKLIYOR', 'ATAMACI_ONAYI_BEKLIYOR');
CREATE UNIQUE INDEX takas_hedef_acik_uk ON takas_talebi (hedef_atama_id) WHERE hedef_atama_id IS NOT NULL AND durum IN ('KARSI_ONAY_BEKLIYOR', 'ATAMACI_ONAYI_BEKLIYOR');
CREATE INDEX takas_kaynak_makinist_idx ON takas_talebi (kaynak_makinist_id);
CREATE INDEX takas_hedef_makinist_idx ON takas_talebi (hedef_makinist_id) WHERE hedef_makinist_id IS NOT NULL;

