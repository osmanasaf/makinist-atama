-- Makinist kartı, bröve (araç tipi + hat) ve izin. Düz FK; TC kimlik, rapor tanısı ve telefon alanı BİLEREK yok (NFR-07, yalnız belge bitiş tarihleri).
CREATE TABLE makinist (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sicil             VARCHAR(20)  NOT NULL,
    ad_soyad          VARCHAR(120) NOT NULL,
    bagli_gar_id      BIGINT       NOT NULL REFERENCES tanim (id),
    durum             VARCHAR(10)  NOT NULL DEFAULT 'AKTIF',
    ehliyet_bitis     DATE         NOT NULL,
    saglik_bitis      DATE         NOT NULL,
    psikoteknik_bitis DATE         NOT NULL,
    son_surus         DATE,
    versiyon          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT makinist_sicil_uk UNIQUE (sicil),
    CONSTRAINT makinist_durum_ck CHECK (durum IN ('AKTIF', 'ASKIDA', 'PASIF'))
);

CREATE TABLE brove_arac_tipi (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    makinist_id   BIGINT NOT NULL REFERENCES makinist (id),
    arac_tipi_id  BIGINT NOT NULL REFERENCES tanim (id),
    sinav_tarihi  DATE   NOT NULL,
    CONSTRAINT brove_arac_tipi_uk UNIQUE (makinist_id, arac_tipi_id)
);

CREATE TABLE brove_hat (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    makinist_id   BIGINT NOT NULL REFERENCES makinist (id),
    hat_id        BIGINT NOT NULL REFERENCES tanim (id),
    sinav_tarihi  DATE   NOT NULL,
    son_surus     DATE,
    CONSTRAINT brove_hat_uk UNIQUE (makinist_id, hat_id)
);

-- İzin: ilk sürümde doğrudan ONAY girilebilir; talep/onay akışı 1c'de (K-09 yalnız ONAY'ı sayar).
CREATE TABLE izin (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    makinist_id   BIGINT       NOT NULL REFERENCES makinist (id),
    baslangic     DATE         NOT NULL,
    bitis         DATE         NOT NULL,
    tur           VARCHAR(10)  NOT NULL,
    durum         VARCHAR(10)  NOT NULL DEFAULT 'ONAY',
    olusturan     VARCHAR(120) NOT NULL,
    karar_veren   VARCHAR(120),
    CONSTRAINT izin_tur_ck CHECK (tur IN ('YILLIK', 'RAPOR', 'DIGER')),
    CONSTRAINT izin_durum_ck CHECK (durum IN ('TALEP', 'ONAY', 'RED')),
    CONSTRAINT izin_aralik_ck CHECK (bitis >= baslangic)
);

CREATE INDEX izin_makinist_idx ON izin (makinist_id, baslangic);
