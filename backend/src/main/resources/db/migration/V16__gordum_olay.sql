-- atama kimliği sil+ekle ile değiştiği için eski onay yeni atamaya geçmez; geçerlilik atama_id + makinist_id + sefer_id + özet eşleşmesiyle okunur.
-- Demo sıfırlama atama kimliklerini sıfırlar ve CASCADE bu tablolara ulaşmaz: DemoVeriServisi TRUNCATE listesinde ikisi de açıkça vardır.
CREATE TABLE gorev_gordum (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atama_id     BIGINT      NOT NULL,
    makinist_id  BIGINT      NOT NULL,
    sefer_id     BIGINT      NOT NULL,
    ozet         TEXT        NOT NULL,
    zaman        TIMESTAMPTZ NOT NULL,
    CONSTRAINT gorev_gordum_atama_uk UNIQUE (atama_id)
);

-- Neden NOTU saklanmaz (başkasının sağlık bilgisi olabilir); yalnız neden etiketi (Neden enum adı).
CREATE TABLE atama_olayi (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    makinist_id      BIGINT      NOT NULL,
    sefer_id         BIGINT      NOT NULL,
    tur              VARCHAR(20) NOT NULL,
    ozet             TEXT        NOT NULL,
    neden_etiketi    VARCHAR(20),
    zaman            TIMESTAMPTZ NOT NULL,
    kapatildi_zaman  TIMESTAMPTZ,
    CONSTRAINT atama_olayi_tur_ck CHECK (tur IN ('KALDIRILDI', 'DEGISTI_BASKASINA'))
);

CREATE INDEX atama_olayi_makinist_idx ON atama_olayi (makinist_id, zaman);

