-- F2b (MK-43): dış garda konaklama kaydı (yatakhane / otel). Kural motorunu ETKİLEMEZ (yalnız kayıt, öneri ve aylık gece raporu); maliyet alanı yok.
-- Düz FK (JPA ilişkisi yok). Aynı makinistin konaklamalarının kesişmemesi serviste denetlenir (DB EXCLUDE btree_gist yetkisi ister: kullanılmadı).
CREATE TABLE konaklama (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    makinist_id  BIGINT       NOT NULL REFERENCES makinist (id),
    gar_id       BIGINT       NOT NULL REFERENCES tanim (id),
    yer_tipi     VARCHAR(10)  NOT NULL,
    giris        TIMESTAMPTZ  NOT NULL,
    cikis        TIMESTAMPTZ  NOT NULL,
    notu         VARCHAR(200),
    versiyon     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT konaklama_yer_tipi_ck CHECK (yer_tipi IN ('YATAKHANE', 'OTEL', 'DIGER')),
    CONSTRAINT konaklama_sure_ck CHECK (cikis > giris)
);

CREATE INDEX konaklama_makinist_giris_idx ON konaklama (makinist_id, giris);

