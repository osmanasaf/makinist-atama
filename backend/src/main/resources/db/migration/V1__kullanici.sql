-- Kullanıcılar ve kaba kuvvet koruması. Satırda `versiyon` yok: yönetici-only, nadir yazma.
CREATE TABLE kullanici (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eposta          VARCHAR(254) NOT NULL,
    ad_soyad        VARCHAR(120) NOT NULL,
    parola_karma    VARCHAR(100) NOT NULL,
    rol             VARCHAR(20)  NOT NULL,
    aktif           BOOLEAN      NOT NULL DEFAULT TRUE,
    basarisiz_giris INTEGER      NOT NULL DEFAULT 0,
    kilit_bitis     TIMESTAMPTZ,
    CONSTRAINT kullanici_eposta_uk UNIQUE (eposta),
    CONSTRAINT kullanici_eposta_kucuk CHECK (eposta = lower(eposta)),
    CONSTRAINT kullanici_rol_ck CHECK (rol IN ('YONETICI', 'ATAMACI')),
    CONSTRAINT kullanici_basarisiz_ck CHECK (basarisiz_giris >= 0)
);
