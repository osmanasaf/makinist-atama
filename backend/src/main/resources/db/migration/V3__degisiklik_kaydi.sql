-- Değişiklik kaydı (MK-9): kim, ne zaman, ne, eski -> yeni, neden. EK-YALNIZ: UPDATE/DELETE DB tetikleyicisiyle reddedilir.
-- Kullanıcı adı kayıt anında kopyalanır (kullanıcı sonradan yeniden adlandırılsa da kayıt okunur kalır); kullanici_id NULL ve ad 'sistem' = sistem işlemi.
-- makinist_id / sefer_id yalnız süzme içindir ve bilerek FK DEĞİLDİR (atama satırı silinse de kayıt kalır). `ayrinti` JSON metindir, sorgulanmaz.
CREATE TABLE degisiklik_kaydi (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zaman         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    kullanici_id  BIGINT,
    kullanici_adi VARCHAR(120) NOT NULL,
    tur           VARCHAR(30)  NOT NULL,
    varlik_tipi   VARCHAR(20)  NOT NULL,
    varlik_id     BIGINT,
    makinist_id   BIGINT,
    sefer_id      BIGINT,
    eski          TEXT,
    yeni          TEXT,
    neden         VARCHAR(20),
    neden_notu    TEXT,
    ayrinti       TEXT,
    CONSTRAINT degisiklik_neden_ck CHECK (neden IS NULL OR neden IN ('IPTAL', 'GECIKME', 'HASTALIK', 'IZIN', 'BELGE', 'DIGER'))
);

CREATE INDEX degisiklik_zaman_idx ON degisiklik_kaydi (zaman);
CREATE INDEX degisiklik_makinist_idx ON degisiklik_kaydi (makinist_id);
CREATE INDEX degisiklik_sefer_idx ON degisiklik_kaydi (sefer_id);
CREATE INDEX degisiklik_tur_idx ON degisiklik_kaydi (tur);

CREATE FUNCTION degisiklik_kaydi_degismez() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Değişiklik kaydı değiştirilemez ya da silinemez (%)', TG_OP USING ERRCODE = 'restrict_violation';
END
$$;

-- TRUNCATE satır tetikleyicisi çalıştırmaz: test temizliği etkilenmez (bilinçli, MK-9).
CREATE TRIGGER degisiklik_kaydi_degismez BEFORE UPDATE OR DELETE ON degisiklik_kaydi
    FOR EACH ROW EXECUTE FUNCTION degisiklik_kaydi_degismez();
