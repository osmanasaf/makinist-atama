-- Gar, hat ve araç tipi listeleri (MK-11). Tek genel tablo; (tip, ad) benzersiz, Türkçe-duyarsız denetim serviste (AramaMetni).
-- Silme yok: makinist bröve'si, bağlı gar ve sefer tanım id'sine bağlanır; yazım hatası yeniden adlandırarak düzeltilir.
CREATE TABLE tanim (
    id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tip VARCHAR(20)  NOT NULL,
    ad  VARCHAR(100) NOT NULL,
    CONSTRAINT tanim_tip_ck CHECK (tip IN ('GAR', 'HAT', 'ARAC_TIPI')),
    CONSTRAINT tanim_tip_ad_uk UNIQUE (tip, ad)
);
