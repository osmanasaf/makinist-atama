-- Sefer (MK-1, MK-3). Makinist sütunu YOK: atama ayrı `atama` tablosundadır (V7).
-- Anlar timestamptz (UTC saklama). `tarih` = planlanan kalkışın İstanbul günü, DEĞİŞMEZ: gecikme kalkışı ertesi güne taşısa da gün listesinin
-- (panoya asılan gün) ve benzersiz anahtarın tarihi kaymaz. Güncel saat = planlanan + gecikme (planlanan saklı kalır).
CREATE TABLE sefer (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tren_no           VARCHAR(30)  NOT NULL,
    tarih             DATE         NOT NULL,
    kalkis_gar_id     BIGINT       NOT NULL REFERENCES tanim (id),
    varis_gar_id      BIGINT       NOT NULL REFERENCES tanim (id),
    planlanan_kalkis  TIMESTAMPTZ  NOT NULL,
    planlanan_varis   TIMESTAMPTZ  NOT NULL,
    kalkis_gecikme_dk INTEGER      NOT NULL DEFAULT 0,
    varis_gecikme_dk  INTEGER      NOT NULL DEFAULT 0,
    arac_tipi_id      BIGINT       NOT NULL REFERENCES tanim (id),
    hat_id            BIGINT       NOT NULL REFERENCES tanim (id),
    km                NUMERIC(8, 1),
    durum             VARCHAR(10)  NOT NULL DEFAULT 'PLANLI',
    versiyon          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT sefer_tarih_tren_uk UNIQUE (tarih, tren_no),
    CONSTRAINT sefer_durum_ck CHECK (durum IN ('PLANLI', 'IPTAL')),
    CONSTRAINT sefer_gecikme_ck CHECK (kalkis_gecikme_dk >= 0 AND varis_gecikme_dk >= 0),
    CONSTRAINT sefer_sure_ck CHECK (planlanan_varis > planlanan_kalkis AND planlanan_varis <= planlanan_kalkis + INTERVAL '24 hours'),
    CONSTRAINT sefer_km_ck CHECK (km IS NULL OR km >= 0),
    CONSTRAINT sefer_tarih_ck CHECK (tarih = (planlanan_kalkis AT TIME ZONE 'Europe/Istanbul')::date)
);

CREATE INDEX sefer_tarih_idx ON sefer (tarih, planlanan_kalkis);
