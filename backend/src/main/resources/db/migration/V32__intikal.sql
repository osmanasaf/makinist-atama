-- Serbest intikal (MK-104): sistemde sefer olarak kayıtlı OLMAYAN yolla (servis, otobüs, taksi) bir garından diğerine gidiş. Kural motoruna F2b'deki yolculukla aynı görev olarak girer
-- (kural kodu değişmez); atama/sefer tablolarına dokunulmaz. Düz FK (JPA ilişkisi yok). Silme yok: PLANLI | IPTAL (iptal satırı denetim izi için kalır).
-- Çakışma DB'de aranmaz: aynı makinistin örtüşen kayıtları kural motorunun K-10'udur (kural yönetilir).
-- Geri alma: DROP TABLE intikal (yeni tablo; veri dönüşümü yok).
CREATE TABLE intikal (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    makinist_id    BIGINT       NOT NULL REFERENCES makinist (id),
    kalkis_gar_id  BIGINT       NOT NULL REFERENCES tanim (id),
    varis_gar_id   BIGINT       NOT NULL REFERENCES tanim (id),
    kalkis         TIMESTAMPTZ  NOT NULL,
    varis          TIMESTAMPTZ  NOT NULL,
    arac_turu      VARCHAR(10)  NOT NULL,
    notu           VARCHAR(200),
    durum          VARCHAR(8)   NOT NULL DEFAULT 'PLANLI',
    versiyon       BIGINT       NOT NULL DEFAULT 0,
    gordu_zaman    TIMESTAMPTZ,
    gordu_ozet     VARCHAR(300),
    CONSTRAINT intikal_arac_turu_ck CHECK (arac_turu IN ('SERVIS', 'OTOBUS', 'TAKSI', 'DIGER')),
    CONSTRAINT intikal_durum_ck CHECK (durum IN ('PLANLI', 'IPTAL')),
    CONSTRAINT intikal_sure_ck CHECK (varis > kalkis),
    CONSTRAINT intikal_en_uzun_ck CHECK (varis - kalkis <= INTERVAL '24 hours'),
    CONSTRAINT intikal_gar_ck CHECK (kalkis_gar_id <> varis_gar_id)
);

CREATE INDEX intikal_makinist_kalkis_idx ON intikal (makinist_id, kalkis);
