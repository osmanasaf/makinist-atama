-- Atama (MK-1): sefer x makinist x rol. Bir seferin bir ASIL ve en çok bir YARDIMCI makinisti olur; aynı makinist aynı sefere iki kez atanamaz.
-- "Kaldır" = satır silme (geçmiş degisiklik_kaydi'nda kalır). Kırmızı durum SAKLANMAZ, her okumada canlı hesaplanır (MK-5).
-- Faz 1 sonrası relief / yolcu dönüşü için geçiş yolu 03-mimari.md MK-1'dedir (ek migration).
CREATE TABLE atama (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sefer_id      BIGINT       NOT NULL REFERENCES sefer (id),
    makinist_id   BIGINT       NOT NULL REFERENCES makinist (id),
    rol           VARCHAR(10)  NOT NULL DEFAULT 'ASIL',
    atayan        VARCHAR(120) NOT NULL,
    atama_zamani  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    gerekce       TEXT,
    versiyon      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT atama_rol_ck CHECK (rol IN ('ASIL', 'YARDIMCI')),
    CONSTRAINT atama_sefer_makinist_uk UNIQUE (sefer_id, makinist_id),
    CONSTRAINT atama_sefer_rol_uk UNIQUE (sefer_id, rol)
);

CREATE INDEX atama_makinist_idx ON atama (makinist_id);
